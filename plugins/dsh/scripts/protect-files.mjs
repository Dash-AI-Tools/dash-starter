// PreToolUse hook: refuses to write the files that carry secrets, the lockfile
// and the allowance file. A developer can allow the env files and the lockfile
// by writing `env` and/or `lockfile` in `.claude/dsh-allow`.
import { existsSync, readFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

import { repoRoot, toRelative } from './checks.mjs'

export const ALLOW_FILE = '.claude/dsh-allow'

export const RULES = [
  {
    id: 'env',
    reason: 'an environment file holds the secrets of the project',
    test: (path) => /(^|\/)\.env(\.[^/]*)?$/.test(path) && !path.endsWith('.example'),
  },
  {
    id: 'key',
    reason: 'a private key never belongs in an edit',
    test: (path) => /\.(pem|key)$/.test(path),
  },
  {
    id: 'lockfile',
    reason: 'the lockfile is generated by npm, not written by hand',
    test: (path) => /(^|\/)package-lock\.json$/.test(path),
  },
  {
    id: 'allow',
    reason: 'the allowance file is written by the developer',
    test: (path) => path === ALLOW_FILE,
  },
]

// The allowance that releases a rule, if any.
const ALLOWANCE = { env: 'env', lockfile: 'lockfile' }

export function readAllowances(root) {
  const file = join(root, ALLOW_FILE)
  if (!existsSync(file)) return new Set()
  const entries = new Set()
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const value = line.trim()
    if (value && !value.startsWith('#')) entries.add(value)
  }
  return entries
}

export function blockedRule(path, allowances = new Set()) {
  for (const rule of RULES) {
    if (!rule.test(path)) continue
    const allowance = ALLOWANCE[rule.id]
    if (allowance && allowances.has(allowance)) continue
    return rule
  }
  return null
}

const strip = (token) => token.replace(/^['"]|['"]$/g, '')

// The paths a shell command writes to. The list is a heuristic: it covers the
// redirections, `tee`, `cp` and `mv`, and the npm commands that rewrite the
// lockfile.
export function bashTargets(command) {
  const targets = []
  const tokens = command.split(/\s+/).filter(Boolean)

  for (let index = 0; index < tokens.length; index++) {
    const token = tokens[index]
    const redirect = token.match(/^(?:\d*|&)>{1,2}\|?$/)
    if (redirect && tokens[index + 1]) {
      targets.push(strip(tokens[index + 1]))
      continue
    }
    if (token === 'tee') {
      const rest = tokens.slice(index + 1).filter((next) => !next.startsWith('-'))
      if (rest.length) targets.push(strip(rest[0]))
      continue
    }
    if (token === 'cp' || token === 'mv') {
      const rest = tokens.slice(index + 1).filter((next) => !next.startsWith('-'))
      if (rest.length > 1) targets.push(strip(rest[rest.length - 1]))
    }
  }

  if (/(?:^|[;&|]\s*)npm\s+(?:i|install|add|uninstall|remove)\b/.test(command)) {
    targets.push('package-lock.json')
  }

  return targets
}

export function evaluate(input, root = repoRoot()) {
  const allowances = readAllowances(root)
  const cwd = input.cwd || root

  if (input.tool_name === 'Bash') {
    const command = input.tool_input?.command || ''
    for (const target of bashTargets(command)) {
      const rel = toRelative(root, resolve(cwd, target))
      if (rel.startsWith('..')) continue
      const rule = blockedRule(rel, allowances)
      if (rule) return { path: rel, rule, command }
    }
    return null
  }

  const filePath = input.tool_input?.file_path
  if (!filePath) return null
  const rel = toRelative(root, resolve(filePath))
  if (rel.startsWith('..')) return null
  const rule = blockedRule(rel, allowances)
  return rule ? { path: rel, rule } : null
}

export function reason(finding) {
  const lines = [
    `Blocked by the dsh guardrail: \`${finding.path}\` is protected (${finding.rule.reason}).`,
  ]
  if (finding.rule.id === 'env' || finding.rule.id === 'lockfile') {
    lines.push(
      `A developer can allow it with \`! echo ${ALLOWANCE[finding.rule.id]} > ${ALLOW_FILE}\` (a shell command the agent cannot run).`
    )
  }
  return lines.join('\n')
}

export function main(input, root = repoRoot()) {
  const finding = evaluate(input, root)
  if (!finding) return { blocked: false }
  return { blocked: true, reason: reason(finding) }
}

function readInput() {
  try {
    return JSON.parse(readFileSync(0, 'utf8'))
  } catch {
    return {}
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const result = main(readInput())
  if (result.blocked) {
    process.stderr.write(result.reason + '\n')
    process.exit(2)
  }
  process.exit(0)
}
