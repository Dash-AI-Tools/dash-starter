// The OpenCode files of the harness, generated from the Claude Code plugin. The
// agents and the skills of `plugins/dsh` stay the only source: `sync` writes
// `.opencode/agents/dsh/`, `.opencode/commands/dsh/` and the plugin module, and
// `check` fails when they are not what `sync` would write.
//
//   node plugins/dsh/scripts/opencode.mjs sync
//   node plugins/dsh/scripts/opencode.mjs check
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { pathToFileURL } from 'node:url'

import { repoRoot } from './checks.mjs'

export const AGENTS_DIR = '.opencode/agents/dsh'
export const COMMANDS_DIR = '.opencode/commands/dsh'
export const PLUGIN_FILE = '.opencode/plugins/dsh.js'

const SOURCE = 'plugins/dsh'
const SYNC = 'node plugins/dsh/scripts/opencode.mjs sync'

// The tools of a Claude Code agent that OpenCode gates with a permission. An
// agent without one of them gets a `deny` rule for its OpenCode action.
const PERMISSIONS = [
  { action: 'edit', tools: ['Edit', 'Write', 'MultiEdit', 'NotebookEdit'] },
  { action: 'shell', tools: ['Bash'] },
  { action: 'subagent', tools: ['Agent', 'Task'] },
]

// The frontmatter of a Markdown file: `key: value` lines between two `---`.
// The files of the plugin only use plain and quoted scalars.
export function parseFrontmatter(text) {
  const match = text.match(/^---\n([\s\S]*?)\n---\n?/)
  if (!match) return { data: {}, body: text }
  const data = {}
  for (const line of match[1].split('\n')) {
    const entry = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/)
    if (!entry) continue
    const value = entry[2].trim()
    data[entry[1]] = /^(['"]).*\1$/.test(value) ? value.slice(1, -1) : value
  }
  return { data, body: text.slice(match[0].length) }
}

// The prompts name the Claude Code forms: the `dsh:` namespace, the Task tool
// and the files of the plugin. OpenCode namespaces by directory and spawns a
// subagent with its `subagent` tool.
export function rewrite(body) {
  return body
    .replace(/the Task tool, `subagent_type: "dsh:([\w-]+)"`/g, 'the subagent tool, agent `dsh/$1`')
    .replace(/`subagent_type: "dsh:([\w-]+)"`/g, 'the agent `dsh/$1`')
    .replace(/\bthe Task tool\b/g, 'the subagent tool')
    .replace(/plugins\/dsh\/skills\/([^/\s`]+)\/SKILL\.md/g, `${COMMANDS_DIR}/$1.md`)
    .replace(/plugins\/dsh\/agents\/([^\s`]+)\.md/g, `${AGENTS_DIR}/$1.md`)
    .replace(/\bdsh:(?=[a-z<])/g, 'dsh/')
}

function header(source) {
  return `<!-- Generated from ${source} by plugins/dsh/scripts/opencode.mjs. Edit the source, then run \`${SYNC}\`. -->`
}

// A YAML double-quoted scalar: the JSON form of the string is one.
const quote = (value) => JSON.stringify(value)

export function toAgent(text, source) {
  const { data, body } = parseFrontmatter(text)
  const tools = (data.tools || '').split(',').map((tool) => tool.trim())
  const lines = ['---', `description: ${quote(data.description || '')}`, 'mode: subagent']
  const denied = PERMISSIONS.filter((rule) => !rule.tools.some((tool) => tools.includes(tool)))
  if (data.tools && denied.length) {
    lines.push('permissions:')
    for (const rule of denied) {
      lines.push(`  - action: ${rule.action}`, "    resource: '*'", '    effect: deny')
    }
  }
  lines.push('---', '', header(source), '')
  return `${lines.join('\n')}\n${rewrite(body.replace(/^\n+/, ''))}`
}

export function toCommand(text, source) {
  const { data, body } = parseFrontmatter(text)
  const hint = data['argument-hint'] ? ` Arguments: ${data['argument-hint']}.` : ''
  const lines = ['---', `description: ${quote(`${data.description || ''}${hint}`)}`, '---']
  lines.push('', header(source), '')
  return `${lines.join('\n')}\n${rewrite(body.replace(/^\n+/, ''))}`
}

export const PLUGIN_MODULE = [
  '// Generated by plugins/dsh/scripts/opencode.mjs. The guardrails of the harness',
  '// for OpenCode: the module lives in the plugin, next to the hooks of Claude Code.',
  "export { default } from '../../plugins/dsh/scripts/opencode-plugin.mjs'",
  '',
].join('\n')

const markdown = (dir) =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter((name) => name.endsWith('.md'))
        .sort()
    : []

// Every file `sync` writes, by its path from the root of the repository.
export function render(root = repoRoot()) {
  const files = new Map()
  for (const name of markdown(join(root, SOURCE, 'agents'))) {
    const source = `${SOURCE}/agents/${name}`
    files.set(`${AGENTS_DIR}/${name}`, toAgent(readFileSync(join(root, source), 'utf8'), source))
  }
  const skills = join(root, SOURCE, 'skills')
  const names = existsSync(skills) ? readdirSync(skills).sort() : []
  for (const name of names) {
    const source = `${SOURCE}/skills/${name}/SKILL.md`
    if (!existsSync(join(root, source))) continue
    files.set(
      `${COMMANDS_DIR}/${name}.md`,
      toCommand(readFileSync(join(root, source), 'utf8'), source)
    )
  }
  files.set(PLUGIN_FILE, PLUGIN_MODULE)
  return files
}

// The generated directories belong to the generator: a file in them that it
// does not write is left over from a removed agent or command.
function leftovers(root, files) {
  const extra = []
  for (const dir of [AGENTS_DIR, COMMANDS_DIR]) {
    for (const name of markdown(join(root, dir))) {
      if (!files.has(`${dir}/${name}`)) extra.push(`${dir}/${name}`)
    }
  }
  return extra
}

export function check(root = repoRoot()) {
  const files = render(root)
  const missing = []
  const stale = []
  for (const [path, content] of files) {
    const file = join(root, path)
    if (!existsSync(file)) missing.push(path)
    else if (readFileSync(file, 'utf8') !== content) stale.push(path)
  }
  const extra = leftovers(root, files)
  return { ok: !missing.length && !stale.length && !extra.length, missing, stale, extra }
}

export function sync(root = repoRoot()) {
  const files = render(root)
  const written = []
  for (const [path, content] of files) {
    const file = join(root, path)
    if (existsSync(file) && readFileSync(file, 'utf8') === content) continue
    mkdirSync(dirname(file), { recursive: true })
    writeFileSync(file, content)
    written.push(path)
  }
  const removed = leftovers(root, files)
  for (const path of removed) rmSync(join(root, path), { force: true })
  return { written, removed }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const mode = process.argv[2]
  const root = repoRoot()
  if (mode === 'sync') {
    const { written, removed } = sync(root)
    for (const path of written) console.log(`wrote ${path}`)
    for (const path of removed) console.log(`removed ${path}`)
    if (!written.length && !removed.length) console.log('The OpenCode files are up to date.')
  } else if (mode === 'check') {
    const result = check(root)
    if (!result.ok) {
      const lines = [
        ...result.missing.map((path) => `  - missing: ${path}`),
        ...result.stale.map((path) => `  - stale: ${path}`),
        ...result.extra.map((path) => `  - left over: ${path}`),
      ]
      console.error(`The OpenCode files are out of date:\n${lines.join('\n')}\nRun \`${SYNC}\`.`)
      process.exit(1)
    }
    console.log('The OpenCode files are up to date.')
  } else {
    console.error('Usage: node plugins/dsh/scripts/opencode.mjs sync|check')
    process.exit(1)
  }
}
